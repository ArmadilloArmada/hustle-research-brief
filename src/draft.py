"""Draft narrative research brief from collected rows."""

from __future__ import annotations

import os
from collections import defaultdict
from datetime import datetime, timezone
from typing import Any


def draft_brief(config: dict[str, Any], rows: list[dict[str, Any]]) -> str:
    """Return Markdown brief — OpenAI when OPENAI_API_KEY is set, else template."""
    if os.environ.get("OPENAI_API_KEY"):
        try:
            return _llm_brief(config, rows)
        except Exception as exc:  # noqa: BLE001
            template = _template_brief(config, rows)
            return (
                f"<!-- LLM draft failed ({exc}); template narrative below -->\n\n"
                + template
            )
    return _template_brief(config, rows)


def _sku(config: dict[str, Any]) -> dict[str, Any]:
    return config.get("sku") or {}


def _template_brief(config: dict[str, Any], rows: list[dict[str, Any]]) -> str:
    sku = _sku(config)
    title = sku.get("title") or "SaaS Pricing Snapshot"
    niche = sku.get("niche") or "SaaS"
    audience = sku.get("audience") or "founders"
    today = datetime.now(timezone.utc).strftime("%Y-%m-%d")
    demo = bool(config.get("demo"))

    by_product: dict[str, list[dict[str, Any]]] = defaultdict(list)
    for row in rows:
        by_product[str(row.get("product") or row.get("source_name") or "?")].append(row)

    priced = [
        r
        for r in rows
        if str(r.get("price_numeric") or "").strip()
        and str(r.get("status", "")).startswith(("ok", "demo", "fallback"))
    ]
    numeric_prices: list[float] = []
    for r in priced:
        try:
            numeric_prices.append(float(r["price_numeric"]))
        except (TypeError, ValueError):
            pass

    lines: list[str] = [
        f"# {title}",
        "",
        f"**Last updated:** {today}  ",
        f"**Niche:** {niche}  ",
        f"**Audience:** {audience}  ",
        f"**Mode:** {'demo fixtures' if demo else 'live collect'}",
        "",
        "## Executive summary",
        "",
    ]

    products = sorted(by_product.keys())
    if numeric_prices:
        low, high = min(numeric_prices), max(numeric_prices)
        lines.append(
            f"This snapshot covers **{len(products)}** products/sources and "
            f"**{len(priced)}** priced signals. Observed list prices in this run "
            f"span roughly **${low:g}–${high:g}** (USD cues extracted from public pages; "
            f"verify before quoting externally)."
        )
    else:
        lines.append(
            f"This snapshot covers **{len(products)}** products/sources. "
            "Few or no dollar prices were extracted — treat rows as qualitative signals "
            "and re-check primary sources."
        )
    lines.extend(
        [
            "",
            "Sell this as a **digital download SKU** (CSV + brief). Refresh weekly and "
            "bump the last-updated date. Gumroad upload is intentionally out of scope for v1.",
            "",
            "## Product notes",
            "",
        ]
    )

    for product in products:
        product_rows = by_product[product]
        lines.append(f"### {product}")
        lines.append("")
        for row in product_rows[:6]:
            plan = row.get("plan_hint") or "—"
            price = row.get("price_raw") or "n/a"
            status = row.get("status") or ""
            signal = (row.get("signal") or "").replace("\n", " ")
            url = row.get("url") or ""
            lines.append(
                f"- **Plan hint:** {plan} · **Price cue:** {price} · "
                f"**Status:** `{status}`"
            )
            if signal:
                lines.append(f"  - Signal: {signal[:200]}")
            if url:
                lines.append(f"  - Source: {url}")
        lines.append("")

    lines.extend(
        [
            "## How to use this SKU",
            "",
            "1. Review `out/data.csv` for structured rows.",
            "2. Spot-check any price against the live pricing page (selectors drift).",
            "3. Edit voice in this brief; export PDF optionally for marketplace listing.",
            "4. List on Gumroad (or similar) manually; refresh weekly.",
            "",
            "## Compliance",
            "",
            "- Prefer official public pricing pages and RSS only.",
            "- Respect robots.txt / site ToS; this tool does polite HTTP GETs, not browser evasion.",
            "- Extracted prices are heuristics — not contractual quotes.",
            "- Thin or stale content risks marketplace rejection; keep freshness honest.",
            "",
            "---",
            "",
            "*Generated by hustle-research-brief (template narrative). "
            "Set `OPENAI_API_KEY` for an LLM-polished draft.*",
            "",
        ]
    )
    return "\n".join(lines)


def _llm_brief(config: dict[str, Any], rows: list[dict[str, Any]]) -> str:
    from openai import OpenAI

    sku = _sku(config)
    title = sku.get("title") or "SaaS Pricing Snapshot"
    niche = sku.get("niche") or "SaaS"
    audience = sku.get("audience") or "founders"
    today = datetime.now(timezone.utc).strftime("%Y-%m-%d")

    row_lines = []
    for r in rows[:40]:
        row_lines.append(
            f"- {r.get('product')}: plan={r.get('plan_hint')!s} "
            f"price={r.get('price_raw')!s} status={r.get('status')!s} "
            f"signal={str(r.get('signal') or '')[:120]!s} url={r.get('url')!s}"
        )
    table = "\n".join(row_lines) or "(no rows)"

    client = OpenAI()
    prompt = (
        f"Write a concise Markdown research brief titled '{title}' for {audience} "
        f"in the niche '{niche}'. Today is {today}. Use ONLY the facts in the rows; "
        "do not invent prices. Include: executive summary, per-product notes, "
        "how to use as a digital download SKU, and a short compliance note. "
        "No Gumroad upload instructions beyond 'list manually'.\n\nRows:\n"
        f"{table}"
    )
    resp = client.chat.completions.create(
        model=os.environ.get("OPENAI_MODEL", "gpt-4o-mini"),
        messages=[
            {
                "role": "system",
                "content": "You write accurate SaaS pricing research briefs for digital downloads.",
            },
            {"role": "user", "content": prompt},
        ],
        temperature=0.3,
    )
    content = (resp.choices[0].message.content or "").strip()
    if not content:
        return _template_brief(config, rows)
    if not content.lstrip().startswith("#"):
        content = f"# {title}\n\n{content}"
    return content + "\n"
