"""Pack approved brief + CSV into out/export/ for Gumroad free-tier upload."""

from __future__ import annotations

import re
import shutil
import zipfile
from datetime import datetime, timezone
from pathlib import Path
from typing import Any, Literal

from approve import artifact_paths, verify_approval

ExportFormat = Literal["zip", "folder", "both"]


def _slugify(text: str) -> str:
    slug = re.sub(r"[^a-z0-9]+", "-", text.lower()).strip("-")
    return slug or "research-brief"


def pack_name(config: dict[str, Any], when: datetime | None = None) -> str:
    sku = config.get("sku") or {}
    title = str(sku.get("title") or "saas-pricing-snapshot")
    day = (when or datetime.now(timezone.utc)).strftime("%Y-%m-%d")
    return f"{_slugify(title)}-{day}"


def buyer_readme(config: dict[str, Any], approved_at: str) -> str:
    sku = config.get("sku") or {}
    title = sku.get("title") or "SaaS Pricing Snapshot"
    niche = sku.get("niche") or "SaaS"
    audience = sku.get("audience") or "founders"
    return "\n".join(
        [
            f"{title}",
            "=" * len(str(title)),
            "",
            f"Niche: {niche}",
            f"Audience: {audience}",
            f"Pack approved (UTC): {approved_at}",
            "",
            "Contents",
            "--------",
            "- brief.md  — narrative research brief (spot-check prices before citing)",
            "- data.csv  — structured pricing / feed rows from public sources",
            "",
            "Refresh cadence: weekly. Bump last-updated in the brief when you re-list.",
            "Prices are heuristics from public pages — not contractual quotes.",
            "",
            "Generated by hustle-research-brief. Seller uploads this pack manually",
            "to Gumroad (free tier); no API upload is performed by the tool.",
            "",
        ]
    )


def clear_export_dir(export_root: Path) -> None:
    """Remove previous pack folders/zips under out/export/ (keep the directory)."""
    if not export_root.exists():
        return
    for child in export_root.iterdir():
        if child.name == ".gitkeep":
            continue
        if child.is_dir():
            shutil.rmtree(child)
        else:
            child.unlink()


def stage_pack(
    export_root: Path,
    name: str,
    paths: dict[str, Path],
    readme_text: str,
) -> Path:
    pack_dir = export_root / name
    if pack_dir.exists():
        shutil.rmtree(pack_dir)
    pack_dir.mkdir(parents=True, exist_ok=True)
    shutil.copy2(paths["brief"], pack_dir / "brief.md")
    shutil.copy2(paths["csv"], pack_dir / "data.csv")
    (pack_dir / "README.txt").write_text(readme_text, encoding="utf-8")
    return pack_dir


def zip_pack(pack_dir: Path, zip_path: Path) -> Path:
    if zip_path.exists():
        zip_path.unlink()
    with zipfile.ZipFile(zip_path, "w", compression=zipfile.ZIP_DEFLATED) as zf:
        for file_path in sorted(pack_dir.rglob("*")):
            if file_path.is_file():
                zf.write(file_path, arcname=f"{pack_dir.name}/{file_path.relative_to(pack_dir)}")
    return zip_path


def export_pack(
    config: dict[str, Any],
    out_dir: Path,
    *,
    fmt: ExportFormat = "both",
    clean: bool = True,
) -> dict[str, Path]:
    out_cfg = config.get("output") or {}
    export_rel = out_cfg.get("export_dir") or "export"
    export_root = out_dir / export_rel
    export_root.mkdir(parents=True, exist_ok=True)

    record = verify_approval(out_dir, out_cfg)
    paths = artifact_paths(out_dir, out_cfg)
    name = pack_name(config)
    readme = buyer_readme(config, str(record.get("approved_at") or ""))

    if clean:
        clear_export_dir(export_root)

    results: dict[str, Path] = {}
    pack_dir = stage_pack(export_root, name, paths, readme)
    results["folder"] = pack_dir

    if fmt in ("zip", "both"):
        zip_path = export_root / f"{name}.zip"
        results["zip"] = zip_pack(pack_dir, zip_path)

    if fmt == "zip":
        # Keep only the zip for Gumroad single-file upload; drop the folder.
        shutil.rmtree(pack_dir)
        results.pop("folder", None)

    return results
